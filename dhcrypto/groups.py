# NIST SP 800-56A và RFC 7919 cho phép khoá riêng dài tối thiểu gấp đôi mức an
# toàn: nhóm 2048 bít (112 bít an toàn) cần từ 224 bít, nhóm 3072 bít cần từ 256
# bít. Dùng 256 bít cho mọi nhóm, sinh khoá nhanh hơn nhiều so với khoá ~2047 bít.
SHORT_PRIVATE_BITS = 256


def _rfc_group(name, hex_str, source):
    p = int(hex_str, 16)
    return DHGroup(name, p, 2, q=(p - 1) // 2, source=source, private_bits=SHORT_PRIVATE_BITS)


MODP_768 = _rfc_group("MODP 768 bít", _MODP_768_HEX, "RFC 2409 nhóm 1 (không còn an toàn)")
MODP_1024 = _rfc_group("MODP 1024 bít", _MODP_1024_HEX, "RFC 2409 nhóm 2 (không khuyến nghị)")
