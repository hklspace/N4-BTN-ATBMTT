"""Bộ tham số (p, g) cho Diffie–Hellman.

Ký hiệu thống nhất với báo cáo: p là số nguyên tố modulo, g là phần tử sinh,
q là cấp của nhóm con do g sinh ra.

Gồm hai loại:
  - bộ số nhỏ để tính tay và in từng bước;
  - các nhóm chuẩn trong RFC 2409, RFC 3526 (MODP) và RFC 7919 (FFDHE). Các số
    nguyên tố này được tính lại từ công thức trong RFC bằng
    tools/derive_rfc_groups.py và so với OpenSSL trong bộ kiểm thử.

Nhóm RFC đều dùng số nguyên tố an toàn p = 2q + 1 và g = 2, g sinh nhóm con cấp
q. Khoá công khai hợp lệ phải thuộc nhóm con này (y^q ≡ 1 mod p), nhờ đó chặn
được tấn công nhóm con nhỏ.
"""
from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True)
class DHGroup:
    name: str
    p: int                              # số nguyên tố modulo
    g: int                              # phần tử sinh
    q: Optional[int] = None             # cấp nhóm con của g; None nghĩa là p - 1
    source: str = ""
    sample_a: Optional[int] = None      # khoá riêng mẫu, chỉ dùng cho ví dụ nhỏ
    sample_b: Optional[int] = None
    private_bits: Optional[int] = None  # độ dài khoá riêng; None = chọn trong cả nhóm

    @property
    def bits(self) -> int:
        return self.p.bit_length()

    @property
    def order(self) -> int:
        """Cấp của g (số giá trị khoá riêng thực sự khác nhau)."""
        return self.q if self.q else self.p - 1


